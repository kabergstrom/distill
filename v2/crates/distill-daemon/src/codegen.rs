    fn publication_world(
        temp: &tempfile::TempDir,
    ) -> (Arc<SharedStore>, RootedScanner, OutputDirectory) {
        let assets = temp.path().join("assets");
        let output = temp.path().join("generated");
        fs::create_dir(&assets).unwrap();
        let scanner = RootedScanner::new([crate::scanner::AssetRoot::new("main", &assets)])
        .unwrap();
        let output = OutputDirectory::open(&output).unwrap();
        let store = Arc::new(SharedStore::new(
            distill_store::Store::open(StoreConfig::new(temp.path().join("state"))).unwrap(),
        ));
        (store, scanner, output)
    }

    fn generated(asset: u8, bytes: &[u8]) -> GeneratedFile {
        GeneratedFile::new(AssetUuid([asset; 16]), bytes.to_vec())
    }

    #[test]
    fn host_rejected_codegen_context_failures_remain_retryable() {
        assert!(retryable_codegen_callback_failure(
            &CallbackInvokeError::HostRejected("host context panic".to_owned())
        ));
        assert!(!retryable_codegen_callback_failure(
            &CallbackInvokeError::Panicked
        ));
    }

    #[test]
    fn complete_namespace_publishes_diffs_and_skips_unchanged_bytes() {
        let temp = tempfile::tempdir().unwrap();
        let (store, scanner, output) = publication_world(&temp);
        let basis = store.write().input_version();
        let first = generated(1, b"pub const VALUE: u8 = 1;\n");
        let second = generated(2, b"pub const VALUE: u8 = 2;\n");
        let first_path = output.path.join(first.relative_path());
        let second_path = output.path.join(second.relative_path());
        let mut world = CodegenWorld {
            store: Arc::clone(&store),
            scanner,
            output: &output,
        };

        world
            .publish_files(basis, &[first.clone(), second.clone()])
            .unwrap();
        let first_memo = store.write().memo_seq();
        assert_eq!(fs::read(&first_path).unwrap(), first.bytes());
        assert_eq!(fs::read(&second_path).unwrap(), second.bytes());
        assert_eq!(
            fs::read_to_string(output.path.join("mod.rs")).unwrap(),
            concat!(
                "// @generated by distill; do not edit.\n",
                "pub mod sp_01010101010101010101010101010101;\n",
                "pub mod sp_02020202020202020202020202020202;\n"
            )
        );

        world
            .publish_files(basis, &[first.clone(), second])
            .unwrap();
        assert_eq!(store.write().memo_seq(), first_memo);

        world.publish_files(basis, &[first]).unwrap();
        assert!(first_path.exists());
        assert!(!second_path.exists());
        assert_eq!(store.write().codegen_outputs().unwrap().len(), 2);
    }

    #[test]
    fn hand_edits_and_unknown_generated_names_are_never_overwritten() {
        let temp = tempfile::tempdir().unwrap();
        let (store, scanner, output) = publication_world(&temp);
        let basis = store.write().input_version();
        let file = generated(3, b"original\n");
        let target = output.path.join(file.relative_path());
        let mut world = CodegenWorld {
            store: Arc::clone(&store),
            scanner,
            output: &output,
        };
        world.publish_files(basis, &[file]).unwrap();
        let expected = store.write().codegen_outputs().unwrap();

        fs::write(&target, b"human edit\n").unwrap();
        assert!(world
            .publish_files(basis, &[generated(3, b"replacement\n")])
            .unwrap_err()
            .contains("edited outside distill"));
        assert_eq!(fs::read(&target).unwrap(), b"human edit\n");
        assert_eq!(store.write().codegen_outputs().unwrap(), expected);

        fs::write(&target, b"original\n").unwrap();
        fs::write(
            output.path.join("sp_09090909090909090909090909090909.rs"),
            b"unowned\n",
        )
        .unwrap();
        assert!(world
            .publish_files(basis, &[generated(3, b"original\n")])
            .unwrap_err()
            .contains("unowned path"));
    }

    #[test]
    fn authored_context_records_query_and_exact_bundle_read() {
        let temp = tempfile::tempdir().unwrap();
        let assets = temp.path().join("assets");
        fs::create_dir(&assets).unwrap();
        let scanner = RootedScanner::new([crate::scanner::AssetRoot::new("main", &assets)])
        .unwrap();
        let type_uuid = TypeUuid([7; 16]);
        let schema = LogicalSchema {
            root: SchemaNode::Primitive(PrimitiveKind::U8),
        };
        let logical_hash = node_hash(&schema.root).unwrap();
        let asset = AssetUuid([8; 16]);
        let bundle_uuid = BundleUuid([9; 16]);
        let bytes = distill_bundle::write_bundle(&Bundle {
            format_version: 1,
            uuid: bundle_uuid,
            primary: Some("shader".into()),
            schemas: BTreeMap::from([(logical_hash, schema)]),
            assets: BTreeMap::from([(
                "shader".into(),
                AssetEntry {
                    uuid: asset,
                    type_uuid,
                    schema_hash: logical_hash,
                    authoring_only: false,
                    data: AuthoredValue::UInt(7),
                },
            )]),
        })
        .unwrap();
        fs::write(assets.join("shader.bundle"), &bytes).unwrap();
        let store = Arc::new(SharedStore::new(
            distill_store::Store::open(StoreConfig::new(temp.path().join("state"))).unwrap(),
        ));
        let basis = {
            let mut store = store.write();
            let (root, _) = store
                .input_transaction(|transaction| {
                    let root = transaction.intern_root("main")?;
                    transaction.upsert_bundle(&BundleMeta {
                        bundle: bundle_uuid,
                        root,
                        path: "shader.bundle".into(),
                        format_version: 1,
                        content_hash: ContentHash(*blake3::hash(&bytes).as_bytes()),
                        origin: None,
                    })?;
                    transaction.upsert_asset(&AssetRecord {
                        asset,
                        bundle: bundle_uuid,
                        local_id: "shader".into(),
                        type_uuid,
                        logical_hash: LogicalHash(logical_hash.0),
                        authoring_only: false,
                        tags: BTreeMap::new(),
                        served: None,
                    })?;
                    Ok(root)
                })
                .unwrap();
            assert_eq!(root.0, 1);
            store.input_version()
        };
        let mut context = AuthoredCodegenContext::new(Arc::clone(&store), scanner.clone(), basis);
        let results = context
            .query(&AssetQuery {
                authored_type: Some(type_uuid),
                ..AssetQuery::default()
            })
            .unwrap();
        assert_eq!(results, [asset]);
        assert_eq!(
            context.read(asset).unwrap().unwrap().value,
            AuthoredValue::UInt(7)
        );
        assert!(matches!(context.trace[0], TraceOp::Query { .. }));
        assert!(matches!(
            context.trace[1],
            TraceOp::AuthoringRead {
                observed: Observed::Ok(Some(_)),
                ..
            }
        ));

        fs::write(assets.join("shader.bundle"), b"concurrent edit").unwrap();
        let output = OutputDirectory::open(&temp.path().join("generated")).unwrap();
        let world = CodegenWorld {
            store,
            scanner,
            output: &output,
        };
        assert!(!world.observe(&context.trace[1]));
    }

