const GENERATED_HEADER: &str = "// @generated by distill; do not edit.\n";

pub struct CodegenService {
    enabled: bool,
    output: Option<OutputDirectory>,
    coordinator: CodegenCoordinator,
    last_attempted: Option<InputVersion>,
}

impl CodegenService {
    pub fn new(
        daemon: &DaemonCoordinator,
        output_path: impl AsRef<Path>,
        enabled: bool,
    ) -> Result<Self, String> {
        let output = if enabled {
            Some(OutputDirectory::open(output_path.as_ref())?)
        } else {
            None
        };
        let service = Self {
            enabled,
            output,
            coordinator: CodegenCoordinator::default(),
            last_attempted: None,
        };
        let retained_output = service
            .output
            .as_ref()
            .map(|output| output.path.as_path())
            .or_else(|| {
                output_path
                    .as_ref()
                    .is_dir()
                    .then_some(output_path.as_ref())
            });
        if let Some(output_path) = retained_output {
            let scanner = daemon.scanner();
            scanner
                .retain_daemon_owned_directory(DaemonOwnedDirectoryKind::CodegenOutput, output_path)
                .map_err(|error| error.to_string())?;
        }
        Ok(service)
    }

    /// Run at most once for the current input version. A stale attempt is not
    /// remembered, so the coordinator loop can retry after publishing the
    /// filesystem event that made it stale.
    /// Run the pipeline's codegens at `store`'s current version and publish
    /// what they generate, through `store`.
    pub fn run(&mut self, daemon: &DaemonCoordinator, store: &mut Store) -> Result<(), String> {
        if !self.enabled {
            return Ok(());
        }
        let output = self
            .output
            .as_ref()
            .ok_or_else(|| "enabled codegen service has no output directory".to_owned())?;
        output.verify()?;

        // The pipeline compiled for the version this store sees.
        let compiled = daemon.compiled_at(store).map_err(|error| error.to_string())?;
        let snapshot = compiled.pipeline_snapshot();
        let epoch = snapshot.epoch().map_err(|failure| failure.to_string())?;
        let basis = store.input_version();
        if self.last_attempted == Some(basis) {
            return Ok(());
        }
        if epoch.codegen_descriptors().is_empty() {
            self.last_attempted = Some(basis);
            return Ok(());
        }

        let scanner = compiled.scanner().clone();
        let mut context = AuthoredCodegenContext::new(store, scanner.clone(), basis);
        let result = epoch.invoke_codegens(&mut context);
        let trace = context.trace;
        let attempt = match result {
            Ok(files) if !context.stopped => CodegenAttempt::success(basis, trace, files),
            Ok(_) => CodegenAttempt::failure(
                basis,
                trace,
                CodegenFailure::Generation("codegen context stopped after input drift".into()),
            ),
            Err(CallbackInvokeError::Rejected(failure)) => {
                CodegenAttempt::failure(basis, trace, failure)
            }
            Err(error) => {
                // The epoch remains healthy after a host-owned context panic.
                // Do not latch this basis: the infrastructure fault may be
                // transient and retrying does not repeat a deterministic
                // module rejection.
                if retryable_codegen_callback_failure(&error) {
                    return Err(error.to_string());
                }
                let _ = daemon.sync_runtime_pipeline_failure(store);
                self.last_attempted = Some(basis);
                return Err(error.to_string());
            }
        };
        let mut world = CodegenWorld {
            store,
            scanner,
            output,
        };
        let publication = self.coordinator.finish(attempt, &mut world);
        match publication {
            CodegenPublication::Requeued => Ok(()),
            CodegenPublication::Published { .. } => {
                self.last_attempted = Some(basis);
                Ok(())
            }
            CodegenPublication::Failed(failure) => {
                self.last_attempted = Some(basis);
                Err(failure.to_string())
            }
            CodegenPublication::PublicationFailed(error) => Err(error.to_string()),
        }
    }
}

fn retryable_codegen_callback_failure(error: &CallbackInvokeError<CodegenFailure>) -> bool {
    matches!(error, CallbackInvokeError::HostRejected(_))
}

struct AuthoredCodegenContext<'s> {
    store: &'s StoreReader,
    scanner: RootedScanner,
    basis: InputVersion,
    trace: Vec<TraceOp>,
    stopped: bool,
}

impl<'s> AuthoredCodegenContext<'s> {
    fn new(store: &'s StoreReader, scanner: RootedScanner, basis: InputVersion) -> Self {
        Self {
            store,
            scanner,
            basis,
            trace: Vec::new(),
            stopped: false,
        }
    }

    fn stop<T>(&mut self, error: impl Into<String>) -> Result<T, CodegenContextError> {
        self.stopped = true;
        Err(CodegenContextError::Failed(error.into()))
    }

    fn check_basis(&mut self, store: &StoreReader) -> Result<(), CodegenContextError> {
        if self.stopped {
            return Err(CodegenContextError::AttemptStopped);
        }
        if store.input_version() != self.basis {
            self.stopped = true;
            return Err(CodegenContextError::AttemptStopped);
        }
        Ok(())
    }
}

impl PipelineCodegenContext for AuthoredCodegenContext<'_> {
    fn query(&mut self, query: &AssetQuery) -> Result<Vec<AssetUuid>, CodegenContextError> {
        if self.stopped {
            return Err(CodegenContextError::AttemptStopped);
        }
        let query = match query.clone().close(None) {
            Ok(query) => query,
            Err(error) => {
                self.stopped = true;
                return Err(CodegenContextError::InvalidQuery(error));
            }
        };
        if query.terminal_type.is_some() {
            return self.stop("target-dependent terminal_type is unavailable to Rust codegen");
        }
        let result = {
            let store = self.store;
            self.check_basis(store)?;
            query_results(store, &query).map_err(CodegenContextError::Failed)?
        };
        self.trace.push(TraceOp::Query {
            query: Box::new(query),
            observed: Observed::Ok(asset_query_result_hash(&result)),
        });
        Ok(result)
    }

    fn read(&mut self, asset: AssetUuid) -> Result<Option<CodegenAsset>, CodegenContextError> {
        if self.stopped {
            return Err(CodegenContextError::AttemptStopped);
        }
        let loaded = {
            let store = self.store;
            self.check_basis(store)?;
            load_authored_asset(store, &self.scanner, asset)
        };
        let (observed, value) = match loaded {
            Ok(Some((hash, value))) => (Observed::Ok(Some(hash)), Some(value)),
            Ok(None) => (Observed::Ok(None), None),
            Err(error) => return self.stop(error),
        };
        self.trace.push(TraceOp::AuthoringRead { asset, observed });
        Ok(value)
    }
}

struct CodegenWorld<'a> {
    store: &'a mut Store,
    scanner: RootedScanner,
    output: &'a OutputDirectory,
}

impl CodegenSnapshot<InputVersion> for CodegenWorld<'_> {
    fn current_basis(&self) -> InputVersion {
        self.store.input_version()
    }

    fn observe(&self, op: &TraceOp) -> bool {
        let store: &StoreReader = self.store;
        match op {
            TraceOp::Query { query, observed } => query_results(store, query)
                .map(|results| Observed::Ok(asset_query_result_hash(&results)) == *observed)
                .unwrap_or(false),
            TraceOp::AuthoringRead { asset, observed } => {
                observe_authored_asset(store, &self.scanner, *asset)
                    .map(|actual| Observed::Ok(actual) == *observed)
                    .unwrap_or(false)
            }
            _ => false,
        }
    }
}

impl CodegenPublisher<InputVersion> for CodegenWorld<'_> {
    fn publish(
        &mut self,
        attempted_basis: &InputVersion,
        files: &[GeneratedFile],
    ) -> Result<(), PublicationError> {
        self.publish_files(*attempted_basis, files)
            .map_err(PublicationError::new)
    }
}

impl CodegenWorld<'_> {
    /// Write the changed generated files, then commit the new expected
    /// pre-images. A crash between the two leaves files that already hold
    /// the proposed bytes; the next publication of the same namespace
    /// accepts them and commits the rows.
    fn publish_files(
        &mut self,
        basis: InputVersion,
        files: &[GeneratedFile],
    ) -> Result<(), String> {
        let output = self.output;
        output.verify()?;
        // The basis check, the file writes and the rows share one write
        // transaction.
        self.store.write_transaction_with(|error| error.to_string(), |store| {
            if store.input_version() != basis {
                return Err("codegen input version changed before publication".into());
            }
            let previous = store.codegen_outputs().map_err(|error| error.to_string())?;
            let desired = desired_namespace(files)?;
            let proposed = desired
                .iter()
                .map(|(path, bytes)| (path.clone(), content_hash(bytes)))
                .collect::<BTreeMap<_, _>>();
            let current = Self::verify_preimages(output, &previous, &proposed)?;

            for change in publication_changes(&previous, &desired, &proposed, &output.path) {
                let relative = change
                    .target
                    .file_name()
                    .and_then(OsStr::to_str)
                    .unwrap_or_default();
                let on_disk = current.get(relative).copied().flatten();
                if on_disk == proposed.get(relative).copied() {
                    continue;
                }
                output.verify()?;
                match change.bytes.as_deref() {
                    Some(bytes) => atomic_write_expecting(&change.target, bytes, on_disk.into()),
                    None => remove_expecting(&change.target, on_disk.map_or(Expected::Absent, Expected::Hash)),
                }
                .map_err(|error| error.to_string())?;
            }
            if previous != proposed {
                store
                    .commit_codegen_outputs(&previous, &proposed)
                    .map_err(|error| error.to_string())?;
            }
            Ok(())
        })
    }

    /// Check that every generated path holds either its recorded pre-image
    /// or the proposed bytes (a publication cut short before its rows were
    /// committed), and return what each one holds now.
    fn verify_preimages(
        output: &OutputDirectory,
        previous: &BTreeMap<String, ContentHash>,
        proposed: &BTreeMap<String, ContentHash>,
    ) -> Result<BTreeMap<String, Option<ContentHash>>, String> {
        let mut current = BTreeMap::new();
        for relative in previous.keys().chain(proposed.keys()) {
            if current.contains_key(relative) {
                continue;
            }
            let target = output.path.join(relative);
            let actual = output.read_owned(&target)?.map(|bytes| content_hash(&bytes));
            let recorded = previous.get(relative).copied();
            if actual != recorded && actual != proposed.get(relative).copied() {
                return Err(match recorded {
                    Some(_) => format!("generated file {} was edited outside distill", target.display()),
                    None => format!("unowned path {} occupies the generated namespace", target.display()),
                });
            }
            current.insert(relative.clone(), actual);
        }
        for entry in output.entry_names()?
 {
            let Some(name) = entry.to_str().map(str::to_owned) else {
                continue;
            };
            let is_generated_name = name == "mod.rs" || validate_unit_path(&name).is_ok();
            if is_generated_name && !previous.contains_key(&name) && !proposed.contains_key(&name) {
                return Err(format!(
                    "unowned path {} occupies the generated namespace",
                    output.path.join(entry).display()
                ));
            }
        }
        Ok(current)
    }
}

struct GeneratedChange {
    target: PathBuf,
    bytes: Option<Vec<u8>>,
}

fn publication_changes(
    previous: &BTreeMap<String, ContentHash>,
    desired: &BTreeMap<String, Vec<u8>>,
    proposed: &BTreeMap<String, ContentHash>,
    output: &Path,
) -> Vec<GeneratedChange> {
    let mut paths = previous
        .keys()
        .chain(proposed.keys())
        .cloned()
        .collect::<Vec<_>>();
    paths.sort();
    paths.dedup();
    paths
        .into_iter()
        .filter_map(|path| {
            let before = previous.get(&path).copied();
            let after = proposed.get(&path).copied();
            (before != after).then(|| GeneratedChange {
                target: output.join(&path),
                bytes: desired.get(&path).cloned(),
            })
        })
        .collect()
}

fn desired_namespace(files: &[GeneratedFile]) -> Result<BTreeMap<String, Vec<u8>>, String> {
    let mut desired = BTreeMap::new();
    let mut modules = Vec::with_capacity(files.len());
    for file in files {
        validate_unit_path(file.relative_path())?;
        if desired
            .insert(file.relative_path().to_owned(), file.bytes().to_vec())
            .is_some()
        {
            return Err(format!(
                "duplicate generated path {} reached the publisher",
                file.relative_path()
            ));
        }
        modules.push(file.relative_path().trim_end_matches(".rs").to_owned());
    }
    modules.sort();
    let mut module = String::from(GENERATED_HEADER);
    for name in modules {
        module.push_str("pub mod ");
        module.push_str(&name);
        module.push_str(";\n");
    }
    desired.insert("mod.rs".into(), module.into_bytes());
    Ok(desired)
}

fn validate_unit_path(path: &str) -> Result<(), String> {
    let Some(hex) = path
        .strip_prefix("sp_")
        .and_then(|path| path.strip_suffix(".rs"))
    else {
        return Err(format!("invalid generated unit path {path:?}"));
    };
    if hex.len() != 32
        || !hex
            .as_bytes()
            .iter()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(byte))
    {
        return Err(format!("invalid generated unit path {path:?}"));
    }
    Ok(())
}

/// The runtime assets `query` selects, as one indexed SQL query. It fails as
/// a read of every entry would: on a tag selector's poisoned index, then on
/// the first unreadable entry (a poisoned bundle's) in UUID order. Only the
/// glob is matched here, after SQL narrowed the rows to its literal prefix.
fn query_results(store: &StoreReader, query: &AssetQuery) -> Result<Vec<AssetUuid>, String> {
    if query.terminal_type.is_some() {
        return Err("target-dependent terminal_type is unavailable to Rust codegen".into());
    }
    if let Some(tag) = &query.tag {
        store
            .check_tag_selector(&tag.tag, tag.value.as_deref(), false)
            .map_err(|error| error.to_string())?;
    }
    let glob = query
        .path_glob
        .as_ref()
        .map(|pattern| {
            globset::Glob::new(pattern)
                .map(|glob| glob.compile_matcher())
                .map_err(|error| error.to_string())
        })
        .transpose()?;
    store.check_entries().map_err(|error| error.to_string())?;
    let mut path_prefixes = query.path_prefix.iter().cloned().collect::<Vec<_>>();
    if let Some(literal) = query
        .path_glob
        .as_deref()
        .map(crate::importer::glob_literal_prefix)
        .filter(|literal| !literal.is_empty())
    {
        path_prefixes.push(literal.to_owned());
    }
    let filter = distill_store::bundles::AssetFilter {
        asset: query.uuid,
        bundle: query.bundle_uuid,
        bundle_path: query.bundle_path.clone(),
        local_id: query.local_id.clone(),
        authored_type: query.authored_type,
        tag: query
            .tag
            .as_ref()
            .map(|tag| (tag.tag.clone(), tag.value.clone())),
        path_prefixes,
        authoring_only: Some(false),
        ..Default::default()
    };
    Ok(store
        .namespace_assets_matching(&filter)
        .map_err(|error| error.to_string())?
        .into_iter()
        .filter(|matched| glob.as_ref().is_none_or(|glob| glob.is_match(&matched.path)))
        .map(|matched| matched.asset)
        .collect())
}

/// The whole-table scan [`query_results`] replaced, kept to pin its results.
#[cfg(test)]
fn query_results_scan(store: &StoreReader, query: &AssetQuery) -> Result<Vec<AssetUuid>, String> {
    if query.terminal_type.is_some() {
        return Err("target-dependent terminal_type is unavailable to Rust codegen".into());
    }
    let tagged = query
        .tag
        .as_ref()
        .map(|tag| {
            store
                .assets_by_tag_value(&tag.tag, tag.value.as_deref())
                .map(|assets| assets.into_iter().collect::<std::collections::BTreeSet<_>>())
        })
        .transpose()
        .map_err(|error| error.to_string())?;
    let bundles = store
        .all_bundles()
        .map_err(|error| error.to_string())?
        .into_iter()
        .map(|bundle| (bundle.bundle, bundle.path))
        .collect::<BTreeMap<_, _>>();
    let glob = query
        .path_glob
        .as_ref()
        .map(|pattern| {
            globset::Glob::new(pattern)
                .map(|glob| glob.compile_matcher())
                .map_err(|error| error.to_string())
        })
        .transpose()?;
    let mut results = Vec::new();
    for asset in store.all_asset_ids().map_err(|error| error.to_string())? {
        let Some(entry) = store.entry(asset).map_err(|error| error.to_string())? else {
            continue;
        };
        if entry.authoring_only
            || query.uuid.is_some_and(|wanted| wanted != asset)
            || query
                .bundle_uuid
                .is_some_and(|wanted| wanted != entry.bundle)
            || query
                .local_id
                .as_ref()
                .is_some_and(|wanted| wanted != &entry.local_id)
            || query
                .authored_type
                .is_some_and(|wanted| wanted != entry.type_uuid)
            || tagged
                .as_ref()
                .is_some_and(|tagged| !tagged.contains(&asset))
        {
            continue;
        }
        let path = bundles
            .get(&entry.bundle)
            .ok_or_else(|| format!("asset {asset} has no owning bundle row"))?;
        if query
            .bundle_path
            .as_ref()
            .is_some_and(|wanted| wanted != path)
            || query
                .path_prefix
                .as_ref()
                .is_some_and(|prefix| !path.starts_with(prefix))
            || glob.as_ref().is_some_and(|glob| !glob.is_match(path))
        {
            continue;
        }
        results.push(asset);
    }
    results.sort_unstable();
    results.dedup();
    Ok(results)
}

fn load_authored_asset(
    store: &StoreReader,
    scanner: &RootedScanner,
    asset: AssetUuid,
) -> Result<Option<(BundleFileHash, CodegenAsset)>, String> {
    let Some(entry) = store.entry(asset).map_err(|error| error.to_string())? else {
        return Ok(None);
    };
    let bundle_meta = store
        .bundle(entry.bundle)
        .map_err(|error| error.to_string())?
        .ok_or_else(|| format!("asset {asset} has no owning bundle row"))?;
    let root = store
        .root_name(bundle_meta.root)
        .map_err(|error| error.to_string())?
        .ok_or_else(|| format!("bundle {} has no root identity", entry.bundle))?;
    let path = scanner
        .physical_path(&root, &bundle_meta.path)
        .map_err(|error| error.to_string())?;
    let bytes = scanner
        .read_identity_checked(&path)
        .map_err(|error| error.to_string())?;
    let hash = BundleFileHash::of_observed_bytes(&bytes);
    if hash.0 != bundle_meta.content_hash.0 {
        return Err(format!(
            "bundle {} changed before its watcher event was published",
            path.display()
        ));
    }
    let bundle = distill_bundle::parse_bundle(&bytes).map_err(|error| error.to_string())?;
    let decoded = bundle
        .assets
        .get(&entry.local_id)
        .ok_or_else(|| format!("asset {asset} is absent from its owning bundle bytes"))?;
    if decoded.uuid != asset || decoded.type_uuid != entry.type_uuid {
        return Err(format!(
            "asset {asset} disagrees with its durable namespace row"
        ));
    }
    Ok(Some((
        hash,
        CodegenAsset {
            asset,
            type_uuid: decoded.type_uuid,
            value: decoded.data.clone(),
        },
    )))
}

fn observe_authored_asset(
    store: &StoreReader,
    scanner: &RootedScanner,
    asset: AssetUuid,
) -> Result<Option<BundleFileHash>, String> {
    load_authored_asset(store, scanner, asset).map(|loaded| loaded.map(|(hash, _)| hash))
}

#[derive(Debug)]
struct OutputDirectory {
    path: PathBuf,
    identity: FileIdentity,
}

impl OutputDirectory {
    fn open(path: &Path) -> Result<Self, String> {
        ensure_real_directory_tree(path)?;
        let link_metadata = fs::symlink_metadata(path)
            .map_err(|error| format!("inspect codegen output {}: {error}", path.display()))?;
        if link_metadata.file_type().is_symlink() || !link_metadata.is_dir() {
            return Err(format!(
                "codegen output {} is not a real directory",
                path.display()
            ));
        }
        let path = fs::canonicalize(path)
            .map_err(|error| format!("canonicalize codegen output {}: {error}", path.display()))?;
        let metadata = fs::metadata(&path)
            .map_err(|error| format!("inspect codegen output {}: {error}", path.display()))?;
        Ok(Self {
            path,
            identity: file_identity(&metadata),
        })
    }

    fn verify(&self) -> Result<(), String> {
        let metadata = fs::symlink_metadata(&self.path).map_err(|error| {
            format!("reinspect codegen output {}: {error}", self.path.display())
        })?;
        let canonical = fs::canonicalize(&self.path).map_err(|error| {
            format!(
                "canonicalize codegen output {}: {error}",
                self.path.display()
            )
        })?;
        if metadata.file_type().is_symlink()
            || !metadata.is_dir()
            || canonical != self.path
            || file_identity(&metadata) != self.identity
        {
            return Err(format!(
                "codegen output directory {} changed",
                self.path.display()
            ));
        }
        Ok(())
    }

    /// Read a generated file, `None` when it does not exist. The path must
    /// be a regular file directly in the output directory, and must not
    /// change while it is read.
    fn read_owned(&self, path: &Path) -> Result<Option<Vec<u8>>, String> {
        self.verify()?;
        let invalid = |detail: &str| format!("generated path {}: {detail}", path.display());
        if path.parent() != Some(self.path.as_path()) {
            return Err(invalid("is outside the flat generated namespace"));
        }
        let opened = match fs::symlink_metadata(path) {
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(error) => return Err(invalid(&error.to_string())),
            Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_file() => {
                return Err(invalid("is not a real regular file"));
            }
            Ok(metadata) => metadata,
        };
        let mut file = File::open(path).map_err(|error| invalid(&error.to_string()))?;
        let mut bytes = Vec::new();
        file.read_to_end(&mut bytes)
            .map_err(|error| invalid(&error.to_string()))?;
        let after = file.metadata().map_err(|error| invalid(&error.to_string()))?;
        let current = fs::symlink_metadata(path).map_err(|error| invalid(&error.to_string()))?;
        if current.file_type().is_symlink()
            || file_identity(&after) != file_identity(&opened)
            || file_identity(&current) != file_identity(&opened)
            || opened.len() != bytes.len() as u64
            || after.len() != bytes.len() as u64
            || opened.modified().ok() != after.modified().ok()
        {
            return Err(invalid("changed while it was read"));
        }
        Ok(Some(bytes))
    }


    fn entry_names(&self) -> Result<Vec<OsString>, String> {
        self.verify()?;
        fs::read_dir(&self.path)
            .map_err(|error| {
                format!(
                    "enumerate generated namespace {}: {error}",
                    self.path.display()
                )
            })?
            .map(|entry| {
                let entry = entry.map_err(|error| error.to_string())?;
                let metadata = fs::symlink_metadata(entry.path()).map_err(|error| {
                    format!(
                        "inspect generated entry {}: {error}",
                        entry.path().display()
                    )
                })?;
                if metadata.file_type().is_symlink() {
                    return Err(format!(
                        "generated entry {} is a symlink",
                        entry.path().display()
                    ));
                }
                Ok(entry.file_name())
            })
            .collect()
    }

}

fn ensure_real_directory_tree(path: &Path) -> Result<(), String> {
    if !path.is_absolute() {
        return Err(format!(
            "codegen output path must be absolute: {}",
            path.display()
        ));
    }
    if path
        .components()
        .any(|component| matches!(component, Component::ParentDir))
    {
        return Err("codegen output path contains a parent component".into());
    }
    // Ancestor aliases (for example macOS /var -> /private/var) are resolved
    // when OutputDirectory stores its canonical path. The final configured
    // entry itself must be a real directory.
    match fs::symlink_metadata(path) {
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => fs::create_dir_all(path)
            .map_err(|error| format!("create codegen output {}: {error}", path.display()))?,
        Err(error) => {
            return Err(format!(
                "inspect codegen output {}: {error}",
                path.display()
            ))
        }
    }
    Ok(())
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct FileIdentity {
    device: u64,
    inode: u64,
}

#[cfg(unix)]
fn file_identity(metadata: &Metadata) -> FileIdentity {
    use std::os::unix::fs::MetadataExt;
    FileIdentity {
        device: metadata.dev(),
        inode: metadata.ino(),
    }
}

/// As the scanner's: the creation time stands in for the file index stable
/// std lacks on Windows.
#[cfg(windows)]
fn file_identity(metadata: &Metadata) -> FileIdentity {
    use std::os::windows::fs::MetadataExt;
    FileIdentity {
        device: 0,
        inode: metadata.creation_time(),
    }
}


