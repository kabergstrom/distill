/// The first line of every generated file, followed by the XXH3-128 (32 hex chars) of the
/// rest of the file. A file whose mark matches its body is distill's own
/// unedited output: whatever publication wrote it, the next one may replace
/// or remove it. The mark is the only record of ownership: the store keeps
/// nothing of the generated files, so a publication cut short part-way
/// leaves nothing to reconcile.
const GENERATED_MARK: &str = "// @generated by distill; do not edit. xxh3:";

/// `body` under its generated mark.
fn certified(body: &[u8]) -> Vec<u8> {
    let mut bytes = Vec::with_capacity(GENERATED_MARK.len() + 33 + body.len());
    bytes.extend_from_slice(GENERATED_MARK.as_bytes());
    bytes.extend_from_slice(distill_core::hash::to_hex(&distill_core::hash::hash(body)).as_bytes());
    bytes.push(b'\n');
    bytes.extend_from_slice(body);
    bytes
}

/// Whether `bytes` carry a generated mark that matches their body.
fn is_certified(bytes: &[u8]) -> bool {
    let Some(rest) = bytes.strip_prefix(GENERATED_MARK.as_bytes()) else {
        return false;
    };
    let (Some(hex), Some(b'\n')) = (rest.get(..32), rest.get(32)) else {
        return false;
    };
    hex == distill_core::hash::to_hex(&distill_core::hash::hash(&rest[33..])).as_bytes()
}

/// What a publication changed, or with [`CodegenService::check_only`] would
/// change, in one generated namespace.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodegenChange {
    /// The generated file, absolute.
    pub path: PathBuf,
    pub kind: CodegenChangeKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum CodegenChangeKind {
    Create,
    Update,
    Delete,
}

impl std::fmt::Display for CodegenChange {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let kind = match self.kind {
            CodegenChangeKind::Create => "create",
            CodegenChangeKind::Update => "update",
            CodegenChangeKind::Delete => "delete",
        };
        write!(formatter, "{kind} {}", self.path.display())
    }
}

/// The `[[codegen.output]]` namespaces (§20), each generated by its
/// registered codegen from the assets under its root.
pub struct CodegenService {
    outputs: Vec<OutputService>,
    /// The pipeline epoch the outputs' installed attempts ran under.
    epoch: Option<u64>,
    /// Publications write nothing (see [`Self::check_only`]).
    check_only: bool,
    /// What publications changed (or would change) since the last
    /// [`Self::take_changes`].
    changes: Vec<CodegenChange>,
}

/// One output namespace: its own directory, installed attempt and
/// attempted basis.
struct OutputService {
    config: CodegenOutputConfig,
    directory: OutputDirectory,
    state: OutputState,
}

#[derive(Default)]
struct OutputState {
    coordinator: CodegenCoordinator,
    last_attempted: Option<InputVersion>,
}

impl CodegenService {
    pub fn new(daemon: &DaemonCoordinator, section: &CodegenSection) -> Result<Self, String> {
        let scanner = daemon.scanner();
        let mut outputs = Vec::with_capacity(section.outputs.len());
        for config in &section.outputs {
            let directory = OutputDirectory::open(&config.rs_mod_path)?;
            scanner
                .retain_daemon_owned_directory(
                    DaemonOwnedDirectoryKind::CodegenOutput,
                    &directory.path,
                )
                .map_err(|error| error.to_string())?;
            outputs.push(OutputService {
                config: config.clone(),
                directory,
                state: OutputState::default(),
            });
        }
        Ok(Self {
            outputs,
            epoch: None,
            check_only: false,
            changes: Vec::new(),
        })
    }

    /// Publish nothing from now on: each publication records what it would
    /// change (see [`Self::take_changes`]) and leaves the files as they are.
    pub fn check_only(&mut self) {
        self.check_only = true;
    }

    /// What the publications since the last call changed, or would have.
    pub fn take_changes(&mut self) -> Vec<CodegenChange> {
        std::mem::take(&mut self.changes)
    }

    /// Run every output's codegen at `store`'s current version and publish
    /// what it generates, through `store`: per output at most once per
    /// input version, and not at all while its last standing attempt's
    /// trace holds. A stale attempt is not remembered, so the coordinator
    /// loop can retry after publishing the filesystem event that made it
    /// stale. One output's failure does not stop the others; the error
    /// names every failed output.
    pub fn run(&mut self, daemon: &DaemonCoordinator, store: &mut Store) -> Result<(), String> {
        self.run_outputs(daemon, store).map(|_| ())
    }

    /// [`Self::run`], answering whether an attempt went stale (it is then
    /// worth running again at once).
    pub(crate) fn run_outputs(
        &mut self,
        daemon: &DaemonCoordinator,
        store: &mut Store,
    ) -> Result<bool, String> {
        if self.outputs.is_empty() {
            return Ok(false);
        }
        for output in &self.outputs {
            output.directory.verify()?;
        }

        // The pipeline compiled for the version this store sees.
        let compiled = daemon
            .compiled_at(store)
            .map_err(|error| error.to_string())?;
        let snapshot = compiled.pipeline_snapshot();
        let epoch = snapshot.epoch().map_err(|failure| failure.to_string())?;
        let basis = store.input_version().map_err(|error| error.to_string())?;
        let scanner = compiled.scanner().clone();
        // An installed outcome stands while its epoch runs and its every
        // observation holds: revalidating the trace costs its reads, a run
        // costs the codegen and the publication's whole namespace.
        if self.epoch != Some(epoch.id()) {
            for output in &mut self.outputs {
                output.state.coordinator = CodegenCoordinator::default();
            }
            self.epoch = Some(epoch.id());
        }
        let descriptors = epoch.codegen_descriptors();
        let mut errors = Vec::new();
        let mut stale = false;
        for output in &mut self.outputs {
            let mut world = CodegenWorld {
                store: &mut *store,
                scanner: scanner.clone(),
                output: &output.directory,
                root: &output.config.root,
                check_only: self.check_only,
                changes: Vec::new(),
            };
            let result =
                output
                    .state
                    .run(&output.config, daemon, &mut world, epoch, &descriptors, basis);
            self.changes.append(&mut world.changes);
            match result {
                Ok(OutputRun::Stale) => stale = true,
                Ok(OutputRun::Done) => {}
                Err(error) => errors.push(format!(
                    "codegen output {} (root {}): {error}",
                    output.config.rs_mod_path.display(),
                    output.config.root
                )),
            }
        }
        if errors.is_empty() {
            Ok(stale)
        } else {
            Err(errors.join("; "))
        }
    }
}

enum OutputRun {
    Done,
    /// The attempt's basis or an observation moved before it published.
    Stale,
}

impl OutputState {
    fn run(
        &mut self,
        config: &CodegenOutputConfig,
        daemon: &DaemonCoordinator,
        world: &mut CodegenWorld<'_>,
        epoch: &crate::epoch::PipelineEpoch,
        descriptors: &[crate::callbacks::CodegenDescriptor],
        basis: InputVersion,
    ) -> Result<OutputRun, String> {
        if self.last_attempted == Some(basis) {
            return Ok(OutputRun::Done);
        }
        if !world.scanner.has_root(&config.root) {
            // A root edit applies live, an output edit at restart.
            self.last_attempted = Some(basis);
            return Err(format!(
                "asset root {:?} is no longer configured; restart the daemon",
                config.root
            ));
        }
        if !descriptors
            .iter()
            .any(|descriptor| descriptor.id == config.codegen)
        {
            self.last_attempted = Some(basis);
            return Err(format!(
                "the pipeline module registers no codegen {:?}",
                config.codegen
            ));
        }
        if self.coordinator.holds(&*world) {
            self.last_attempted = Some(basis);
            return Ok(OutputRun::Done);
        }
        let mut context =
            AuthoredCodegenContext::new(world.store, world.scanner.clone(), basis, world.root);
        let result = epoch.invoke_codegen(&config.codegen, &mut context);
        let trace = context.trace;
        let attempt = match result {
            Ok(output) if !context.stopped => CodegenAttempt::success(basis, trace, output),
            Ok(_) => CodegenAttempt::failure(
                basis,
                trace,
                CodegenFailure::Generation("codegen context stopped after input drift".into()),
            ),
            Err(CallbackInvokeError::Rejected(failure)) => {
                CodegenAttempt::failure(basis, trace, failure)
            }
            Err(error) => {
                // The epoch remains healthy after a host-owned context panic.
                // Do not latch this basis: the infrastructure fault may be
                // transient and retrying does not repeat a deterministic
                // module rejection.
                if retryable_codegen_callback_failure(&error) {
                    return Err(error.to_string());
                }
                let _ = daemon.sync_runtime_pipeline_failure(world.store);
                self.last_attempted = Some(basis);
                return Err(error.to_string());
            }
        };
        match self.coordinator.finish(attempt, world) {
            CodegenPublication::Requeued => Ok(OutputRun::Stale),
            CodegenPublication::Published { .. } => {
                self.last_attempted = Some(basis);
                Ok(OutputRun::Done)
            }
            CodegenPublication::Failed(failure) => {
                self.last_attempted = Some(basis);
                Err(failure.to_string())
            }
            CodegenPublication::PublicationFailed(error) => Err(error.to_string()),
        }
    }
}

fn retryable_codegen_callback_failure(error: &CallbackInvokeError<CodegenFailure>) -> bool {
    matches!(error, CallbackInvokeError::HostRejected(_))
}

struct AuthoredCodegenContext<'s> {
    store: &'s StoreReader,
    scanner: RootedScanner,
    basis: InputVersion,
    /// The root of the output this context serves.
    root: &'s str,
    trace: Vec<TraceOp>,
    stopped: bool,
}

impl<'s> AuthoredCodegenContext<'s> {
    fn new(
        store: &'s StoreReader,
        scanner: RootedScanner,
        basis: InputVersion,
        root: &'s str,
    ) -> Self {
        Self {
            store,
            scanner,
            basis,
            root,
            trace: Vec::new(),
            stopped: false,
        }
    }

    fn stop<T>(&mut self, error: impl Into<String>) -> Result<T, CodegenContextError> {
        self.stopped = true;
        Err(CodegenContextError::Failed(error.into()))
    }

    fn check_basis(&mut self, store: &StoreReader) -> Result<(), CodegenContextError> {
        if self.stopped {
            return Err(CodegenContextError::AttemptStopped);
        }
        if store
            .input_version()
            .map_err(|error| CodegenContextError::Failed(error.to_string()))?
            != self.basis
        {
            self.stopped = true;
            return Err(CodegenContextError::AttemptStopped);
        }
        Ok(())
    }
}

impl PipelineCodegenContext for AuthoredCodegenContext<'_> {
    fn root(&self) -> &str {
        self.root
    }

    fn query(&mut self, query: &AssetQuery) -> Result<Vec<AssetUuid>, CodegenContextError> {
        if self.stopped {
            return Err(CodegenContextError::AttemptStopped);
        }
        let query = match query.clone().close(None) {
            Ok(query) => query,
            Err(error) => {
                self.stopped = true;
                return Err(CodegenContextError::InvalidQuery(error));
            }
        };
        if query.terminal_type.is_some() {
            return self.stop("target-dependent terminal_type is unavailable to Rust codegen");
        }
        let result = {
            let store = self.store;
            self.check_basis(store)?;
            query_results(store, &query, self.root).map_err(CodegenContextError::Failed)?
        };
        self.trace.push(TraceOp::Query {
            query: Box::new(query),
            observed: Observed::Ok(asset_query_result_hash(&result)),
        });
        Ok(result)
    }

    fn read(&mut self, asset: AssetUuid) -> Result<Option<CodegenAsset>, CodegenContextError> {
        if self.stopped {
            return Err(CodegenContextError::AttemptStopped);
        }
        let loaded = {
            let store = self.store;
            self.check_basis(store)?;
            load_authored_asset(store, &self.scanner, asset, self.root)
        };
        let (observed, value) = match loaded {
            Ok(Some((hash, value))) => (Observed::Ok(Some(hash)), Some(value)),
            Ok(None) => (Observed::Ok(None), None),
            Err(error) => return self.stop(error),
        };
        self.trace.push(TraceOp::AuthoringRead { asset, observed });
        Ok(value)
    }
}

struct CodegenWorld<'a> {
    store: &'a mut Store,
    scanner: RootedScanner,
    output: &'a OutputDirectory,
    /// The root of the output this world publishes.
    root: &'a str,
    /// Record changes, write nothing.
    check_only: bool,
    /// What the last publication changed, or would have.
    changes: Vec<CodegenChange>,
}

impl CodegenSnapshot<InputVersion> for CodegenWorld<'_> {
    fn current_basis(&self) -> Option<InputVersion> {
        self.store.input_version().ok()
    }

    fn observe(&self, op: &TraceOp) -> bool {
        let store: &StoreReader = self.store;
        match op {
            TraceOp::Query { query, observed } => query_results(store, query, self.root)
                .map(|results| Observed::Ok(asset_query_result_hash(&results)) == *observed)
                .unwrap_or(false),
            TraceOp::AuthoringRead { asset, observed } => {
                observe_authored_asset(store, &self.scanner, *asset, self.root)
                    .map(|actual| Observed::Ok(actual) == *observed)
                    .unwrap_or(false)
            }
            _ => false,
        }
    }
}

impl CodegenPublisher<InputVersion> for CodegenWorld<'_> {
    fn publish(
        &mut self,
        attempted_basis: &InputVersion,
        output: &CodegenOutput,
    ) -> Result<(), PublicationError> {
        self.publish_files(*attempted_basis, output)
            .map_err(PublicationError::new)
    }
}

impl CodegenWorld<'_> {
    /// Bring every generated file to the proposed bytes. A crash part-way
    /// leaves generated files that carry their mark (`GENERATED_MARK`); the
    /// next publication, of this namespace or any other, owns them. A file
    /// whose bytes are already the proposed ones is not touched.
    fn publish_files(&mut self, basis: InputVersion, output: &CodegenOutput) -> Result<(), String> {
        let directory = self.output;
        let check_only = self.check_only;
        directory.verify()?;
        let mut changes = Vec::new();
        // The basis check and the file writes share one write transaction.
        self.store.write_transaction_with(
            |error| error.to_string(),
            |store| {
                if store.input_version().map_err(|error| error.to_string())? != basis {
                    return Err("codegen input version changed before publication".into());
                }
                let desired = desired_namespace(output)?;
                let current = Self::owned_files(directory, &desired)?;

                for (relative, &on_disk) in &current {
                    let bytes = desired.get(relative);
                    if on_disk == bytes.map(|bytes| content_hash(bytes)) {
                        continue;
                    }
                    let target = directory.path.join(relative);
                    let kind = match (on_disk, bytes) {
                        (None, _) => CodegenChangeKind::Create,
                        (Some(_), Some(_)) => CodegenChangeKind::Update,
                        (Some(_), None) => CodegenChangeKind::Delete,
                    };
                    changes.push(CodegenChange {
                        path: target.clone(),
                        kind,
                    });
                    if check_only {
                        continue;
                    }
                    directory.verify()?;
                    match bytes {
                        Some(bytes) => {
                            atomic_file::write(&directory.path, &target, bytes, on_disk.into())
                        }
                        None => atomic_file::remove(&target, Expected::from(on_disk)),
                    }
                    .map_err(|error| error.to_string())?;
                }
                Ok(())
            },
        )?;
        self.changes = changes;
        Ok(())
    }

    /// What every generated name holds now, the desired ones and those the
    /// output directory holds, once each is checked to be distill's: absent,
    /// or carrying its generated mark. Anything else is a hand edit or an
    /// unowned file.
    fn owned_files(
        output: &OutputDirectory,
        desired: &BTreeMap<String, Vec<u8>>,
    ) -> Result<BTreeMap<String, Option<ContentHash>>, String> {
        let mut names = desired.keys().cloned().collect::<BTreeSet<_>>();
        for entry in output.entry_names()? {
            if let Some(name) = entry.to_str() {
                if name == "mod.rs" || validate_unit_path(name).is_ok() {
                    names.insert(name.to_owned());
                }
            }
        }
        let mut current = BTreeMap::new();
        for relative in names {
            let target = output.path.join(&relative);
            let bytes = output.read_owned(&target)?;
            match bytes.as_deref() {
                None => {}
                Some(bytes) if is_certified(bytes) => {}
                Some(bytes) if bytes.starts_with(GENERATED_MARK.as_bytes()) => {
                    return Err(format!(
                        "generated file {} was edited outside distill",
                        target.display()
                    ))
                }
                Some(_) => {
                    return Err(format!(
                        "unowned path {} occupies the generated namespace",
                        target.display()
                    ))
                }
            }
            current.insert(relative, bytes.as_deref().map(content_hash));
        }
        Ok(current)
    }
}

/// Every generated file's path and exact bytes, each under its generated
/// mark. `mod.rs` holds, each section ending in a newline and the
/// sections apart by a blank line: the codegen's preamble, the module
/// lines by physical name (`pub mod sp_<hex>;`; for an aliased file
/// `#[doc(hidden)]` and `pub use self::sp_<hex> as <alias>;`, since a
/// private module cannot be re-exported), and the codegen's items. An
/// empty section is left out.
fn desired_namespace(output: &CodegenOutput) -> Result<BTreeMap<String, Vec<u8>>, String> {
    let mut desired = BTreeMap::new();
    let mut modules = Vec::with_capacity(output.files.len());
    for file in &output.files {
        validate_unit_path(file.relative_path())?;
        if desired
            .insert(file.relative_path().to_owned(), certified(file.bytes()))
            .is_some()
        {
            return Err(format!(
                "duplicate generated path {} reached the publisher",
                file.relative_path()
            ));
        }
        modules.push((file.module_name(), file.alias()));
    }
    modules.sort();
    let mut lines = String::new();
    for (name, alias) in modules {
        match alias {
            Some(alias) => {
                lines.push_str(&format!("#[doc(hidden)]\npub mod {name};\npub use self::{name} as {alias};\n"));
            }
            None => lines.push_str(&format!("pub mod {name};\n")),
        }
    }
    let mut module = String::new();
    for section in [output.mod_preamble.as_str(), &lines, output.mod_items.as_str()] {
        if section.is_empty() {
            continue;
        }
        if !module.is_empty() {
            module.push('\n');
        }
        module.push_str(section);
        if !section.ends_with('\n') {
            module.push('\n');
        }
    }
    desired.insert("mod.rs".into(), certified(module.as_bytes()));
    Ok(desired)
}

fn validate_unit_path(path: &str) -> Result<(), String> {
    let Some(hex) = path
        .strip_prefix("sp_")
        .and_then(|path| path.strip_suffix(".rs"))
    else {
        return Err(format!("invalid generated unit path {path:?}"));
    };
    if hex.len() != 32
        || !hex
            .as_bytes()
            .iter()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(byte))
    {
        return Err(format!("invalid generated unit path {path:?}"));
    }
    Ok(())
}

/// The runtime assets `query` selects, as one asset query (DESIGN.md §13,
/// asset queries): it fails naming the poisoned bundles it reaches, through
/// a poisoned bundle's skeleton or a poisoned tag index. Only the glob is
/// matched here, after SQL narrowed the rows by its keys. Only the bundles
/// under the asset root `root` answer, and only their poisons fail it.
fn query_results(
    store: &StoreReader,
    query: &AssetQuery,
    root: &str,
) -> Result<Vec<AssetUuid>, String> {
    if query.terminal_type.is_some() {
        return Err("target-dependent terminal_type is unavailable to Rust codegen".into());
    }
    let glob = query
        .path_glob
        .as_ref()
        .map(|pattern| {
            globset::Glob::new(pattern)
                .map(|glob| glob.compile_matcher())
                .map_err(|error| error.to_string())
        })
        .transpose()?;
    let Some(root) = store.root_id(root).map_err(|error| error.to_string())? else {
        // No bundle was ever published under the root.
        return Ok(Vec::new());
    };
    let filter = distill_store::bundles::AssetFilter {
        root: Some(root),
        ..crate::build::runtime_asset_filter(query)
    };
    let answer = store
        .namespace_assets_matching(&filter, |path| {
            glob.as_ref().is_none_or(|glob| glob.is_match(path))
        })
        .map_err(|error| error.to_string())?;
    match answer {
        Ok(matched) => Ok(matched.into_iter().map(|matched| matched.asset).collect()),
        Err(bundles) => Err(format!("asset query reaches poisoned bundles {bundles:?}")),
    }
}

/// The whole-table scan [`query_results`] replaced, kept to pin its results.
/// `skeletons` are the poisoned bundles' skeleton entries, with their
/// bundle and path (an entry read cannot see them).
#[cfg(test)]
fn query_results_scan(
    store: &StoreReader,
    query: &AssetQuery,
    skeletons: &[(BundleUuid, String, distill_store::bundles::SkeletonEntry)],
) -> Result<Vec<AssetUuid>, String> {
    if query.terminal_type.is_some() {
        return Err("target-dependent terminal_type is unavailable to Rust codegen".into());
    }
    let bundles = store
        .all_bundles()
        .map_err(|error| error.to_string())?
        .into_iter()
        .map(|bundle| (bundle.bundle, bundle.path))
        .collect::<BTreeMap<_, _>>();
    let glob = query
        .path_glob
        .as_ref()
        .map(|pattern| {
            globset::Glob::new(pattern)
                .map(|glob| glob.compile_matcher())
                .map_err(|error| error.to_string())
        })
        .transpose()?;
    // Whether a runtime row meets every selector, its tag too unless
    // `untagged`.
    let selects = |asset: AssetUuid,
                   bundle: BundleUuid,
                   path: &str,
                   local_id: &str,
                   type_uuid: TypeUuid,
                   tags: &BTreeMap<String, Option<String>>,
                   untagged: bool| {
        query.uuid.is_none_or(|wanted| wanted == asset)
            && query.bundle_uuid.is_none_or(|wanted| wanted == bundle)
            && query
                .local_id
                .as_ref()
                .is_none_or(|wanted| wanted == local_id)
            && query.authored_type.is_none_or(|wanted| wanted == type_uuid)
            && (untagged
                || query.tag.as_ref().is_none_or(|tag| {
                    tags.get(&tag.tag).is_some_and(|value| {
                        tag.value.is_none() || value.as_ref() == tag.value.as_ref()
                    })
                }))
            && query
                .bundle_path
                .as_ref()
                .is_none_or(|wanted| wanted == path)
            && query
                .path_prefix
                .as_ref()
                .is_none_or(|prefix| path.starts_with(prefix))
            && glob.as_ref().is_none_or(|glob| glob.is_match(path))
    };
    let mut poisoned = std::collections::BTreeSet::new();
    for (bundle, path, entry) in skeletons {
        if !entry.authoring_only
            && selects(
                entry.asset,
                *bundle,
                path,
                &entry.local_id,
                entry.type_uuid,
                &entry.tags,
                false,
            )
        {
            poisoned.insert(*bundle);
        }
    }
    let mut results = Vec::new();
    for asset in store.all_asset_ids().map_err(|error| error.to_string())? {
        let entry = match store.entry(asset) {
            Ok(Some(entry)) => entry,
            Ok(None) | Err(distill_store::StoreError::BundlePoisoned { .. }) => continue,
            Err(error) => return Err(error.to_string()),
        };
        if entry.authoring_only {
            continue;
        }
        let path = bundles
            .get(&entry.bundle)
            .ok_or_else(|| format!("asset {asset} has no owning bundle row"))?;
        let selects = |untagged| {
            selects(
                asset,
                entry.bundle,
                path,
                &entry.local_id,
                entry.type_uuid,
                &entry.tags,
                untagged,
            )
        };
        if query.tag.is_some()
            && selects(true)
            && store
                .tag_index_state(asset)
                .map_err(|error| error.to_string())?
                .is_some_and(|state| state.poison.is_some())
        {
            poisoned.insert(entry.bundle);
        }
        if selects(false) {
            results.push(asset);
        }
    }
    if !poisoned.is_empty() {
        let bundles = poisoned.into_iter().collect::<Vec<_>>();
        return Err(format!("asset query reaches poisoned bundles {bundles:?}"));
    }
    results.sort_unstable();
    Ok(results)
}

/// `asset`'s authored value, read from its bundle's bytes, with the bytes'
/// hash; `None` when no bundle under the asset root `root` holds it.
fn load_authored_asset(
    store: &StoreReader,
    scanner: &RootedScanner,
    asset: AssetUuid,
    root: &str,
) -> Result<Option<(BundleFileHash, CodegenAsset)>, String> {
    let Some((entry, bundle_meta)) = store
        .entry_with_bundle(asset)
        .map_err(|error| error.to_string())?
    else {
        return Ok(None);
    };
    let bundle_meta =
        bundle_meta.ok_or_else(|| format!("asset {asset} has no owning bundle row"))?;
    let bundle_root = store
        .root_name(bundle_meta.root)
        .map_err(|error| error.to_string())?
        .ok_or_else(|| format!("bundle {} has no root identity", entry.bundle))?;
    if bundle_root != root {
        return Ok(None);
    }
    let path = scanner
        .physical_path(&bundle_root, &bundle_meta.path)
        .map_err(|error| error.to_string())?;
    let bytes = scanner
        .read_identity_checked(&path)
        .map_err(|error| error.to_string())?;
    let hash = BundleFileHash::of_observed_bytes(&bytes);
    if hash.0 != bundle_meta.content_hash.0 {
        return Err(format!(
            "bundle {} changed before its watcher event was published",
            path.display()
        ));
    }
    let bundle = distill_bundle::parse_bundle(&bytes).map_err(|error| error.to_string())?;
    let decoded = bundle
        .assets
        .get(&entry.local_id)
        .ok_or_else(|| format!("asset {asset} is absent from its owning bundle bytes"))?;
    if decoded.uuid != asset || decoded.type_uuid != entry.type_uuid {
        return Err(format!(
            "asset {asset} disagrees with its durable namespace row"
        ));
    }
    Ok(Some((
        hash,
        CodegenAsset {
            asset,
            type_uuid: decoded.type_uuid,
            value: decoded.data.clone(),
        },
    )))
}

fn observe_authored_asset(
    store: &StoreReader,
    scanner: &RootedScanner,
    asset: AssetUuid,
    root: &str,
) -> Result<Option<BundleFileHash>, String> {
    load_authored_asset(store, scanner, asset, root).map(|loaded| loaded.map(|(hash, _)| hash))
}

#[derive(Debug)]
struct OutputDirectory {
    path: PathBuf,
    identity: FileIdentity,
}

impl OutputDirectory {
    /// Open the output directory for this process, emptying its staging
    /// directory (`atomic_file::open_staging`): a temp there is a write an
    /// earlier process never committed.
    fn open(path: &Path) -> Result<Self, String> {
        ensure_real_directory_tree(path)?;
        let link_metadata = fs::symlink_metadata(path)
            .map_err(|error| format!("inspect codegen output {}: {error}", path.display()))?;
        if link_metadata.file_type().is_symlink() || !link_metadata.is_dir() {
            return Err(format!(
                "codegen output {} is not a real directory",
                path.display()
            ));
        }
        let path = fs::canonicalize(path)
            .map_err(|error| format!("canonicalize codegen output {}: {error}", path.display()))?;
        let metadata = fs::metadata(&path)
            .map_err(|error| format!("inspect codegen output {}: {error}", path.display()))?;
        atomic_file::open_staging(&path)
            .map_err(|error| format!("open codegen staging in {}: {error}", path.display()))?;
        Ok(Self {
            path,
            identity: file_identity(&metadata),
        })
    }

    fn verify(&self) -> Result<(), String> {
        let metadata = fs::symlink_metadata(&self.path).map_err(|error| {
            format!("reinspect codegen output {}: {error}", self.path.display())
        })?;
        let canonical = fs::canonicalize(&self.path).map_err(|error| {
            format!(
                "canonicalize codegen output {}: {error}",
                self.path.display()
            )
        })?;
        if metadata.file_type().is_symlink()
            || !metadata.is_dir()
            || canonical != self.path
            || file_identity(&metadata) != self.identity
        {
            return Err(format!(
                "codegen output directory {} changed",
                self.path.display()
            ));
        }
        Ok(())
    }

    /// Read a generated file, `None` when it does not exist. The path must
    /// be a regular file directly in the output directory, and must not
    /// change while it is read.
    fn read_owned(&self, path: &Path) -> Result<Option<Vec<u8>>, String> {
        self.verify()?;
        let invalid = |detail: &str| format!("generated path {}: {detail}", path.display());
        if path.parent() != Some(self.path.as_path()) {
            return Err(invalid("is outside the flat generated namespace"));
        }
        let opened = match fs::symlink_metadata(path) {
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(error) => return Err(invalid(&error.to_string())),
            Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_file() => {
                return Err(invalid("is not a real regular file"));
            }
            Ok(metadata) => metadata,
        };
        let mut file = File::open(path).map_err(|error| invalid(&error.to_string()))?;
        let mut bytes = Vec::new();
        file.read_to_end(&mut bytes)
            .map_err(|error| invalid(&error.to_string()))?;
        let after = file
            .metadata()
            .map_err(|error| invalid(&error.to_string()))?;
        let current = fs::symlink_metadata(path).map_err(|error| invalid(&error.to_string()))?;
        if current.file_type().is_symlink()
            || file_identity(&after) != file_identity(&opened)
            || file_identity(&current) != file_identity(&opened)
            || opened.len() != bytes.len() as u64
            || after.len() != bytes.len() as u64
            || opened.modified().ok() != after.modified().ok()
        {
            return Err(invalid("changed while it was read"));
        }
        Ok(Some(bytes))
    }

    fn entry_names(&self) -> Result<Vec<OsString>, String> {
        self.verify()?;
        fs::read_dir(&self.path)
            .map_err(|error| {
                format!(
                    "enumerate generated namespace {}: {error}",
                    self.path.display()
                )
            })?
            .map(|entry| {
                let entry = entry.map_err(|error| error.to_string())?;
                let metadata = fs::symlink_metadata(entry.path()).map_err(|error| {
                    format!(
                        "inspect generated entry {}: {error}",
                        entry.path().display()
                    )
                })?;
                if metadata.file_type().is_symlink() {
                    return Err(format!(
                        "generated entry {} is a symlink",
                        entry.path().display()
                    ));
                }
                Ok(entry.file_name())
            })
            .collect()
    }
}

fn ensure_real_directory_tree(path: &Path) -> Result<(), String> {
    if !path.is_absolute() {
        return Err(format!(
            "codegen output path must be absolute: {}",
            path.display()
        ));
    }
    if path
        .components()
        .any(|component| matches!(component, Component::ParentDir))
    {
        return Err("codegen output path contains a parent component".into());
    }
    // Ancestor aliases (for example macOS /var -> /private/var) are resolved
    // when OutputDirectory stores its canonical path. The final configured
    // entry itself must be a real directory.
    match fs::symlink_metadata(path) {
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => fs::create_dir_all(path)
            .map_err(|error| format!("create codegen output {}: {error}", path.display()))?,
        Err(error) => {
            return Err(format!(
                "inspect codegen output {}: {error}",
                path.display()
            ))
        }
    }
    Ok(())
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct FileIdentity {
    device: u64,
    inode: u64,
}

#[cfg(unix)]
fn file_identity(metadata: &Metadata) -> FileIdentity {
    use std::os::unix::fs::MetadataExt;
    FileIdentity {
        device: metadata.dev(),
        inode: metadata.ino(),
    }
}

/// As the scanner's: the creation time stands in for the file index stable
/// std lacks on Windows.
#[cfg(windows)]
fn file_identity(metadata: &Metadata) -> FileIdentity {
    use std::os::windows::fs::MetadataExt;
    FileIdentity {
        device: 0,
        inode: metadata.creation_time(),
    }
}

