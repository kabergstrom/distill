    fn namespace(filler: u32, damage: Damage) -> (tempfile::TempDir, Store) {
        let dir = tempfile::tempdir().unwrap();
        let mut store = Store::open(StoreConfig::new(dir.path().join(".distill"))).unwrap();
        store
            .input_transaction(|txn| {
                let root = txn.intern_root("main")?;
                let paths = PATHS
                    .iter()
                    .map(|path| (*path).to_owned())
                    .chain((0..filler).map(|index| format!("bulk/b{index:05}")));
                for (index, path) in paths.enumerate() {
                    let index = index as u32;
                    let bundle = BundleUuid(uuid(0x10, index));
                    txn.upsert_bundle(&BundleMeta {
                        bundle,
                        root,
                        path,
                        format_version: 1,
                        content_hash: ContentHash([index as u8; 16]),
                        origin: None,
                        import_watched: false,
                    })?;
                    for (entry, authoring_only) in [(1u8, false), (2, true)] {
                        let mut tags = BTreeMap::new();
                        tags.insert(
                            "kind".to_owned(),
                            (index % 3 != 0)
                                .then(|| ["mesh", "rock"][index as usize % 2].to_owned()),
                        );
                        if index % 4 == u32::from(entry) {
                            tags.insert("hero".into(), None);
                        }
                        txn.upsert_asset(&AssetRecord {
                            asset: AssetUuid(uuid(0x20 + entry, index)),
                            bundle,
                            local_id: if entry == 1 { "main" } else { "settings" }.into(),
                            type_uuid: if index % 2 == 0 { MESH } else { TEXTURE },
                            logical_hash: SCHEMA,
                            authoring_only,
                            tags,
                            terminal_type: None,
                            content: None,
                        })?;
                    }
                }
                if let Damage::PendingTagIndex = damage {
                    txn.set_tag_index_pending(AssetUuid(uuid(0x21, 11)))?;
                }
                for (bundle, path, entry) in skeletons(damage) {
                    txn.poison_bundle(
                        &NamespaceSkeleton {
                            bundle,
                            root,
                            path,
                            format_version: 1,
                            content_hash: ContentHash([0xee; 16]),
                            entries: vec![entry],
                        },
                        "malformed",
                    )?;
                }
                Ok(())
            })
            .unwrap();
        (dir, store)
    }

