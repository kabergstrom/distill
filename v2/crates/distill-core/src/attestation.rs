impl From<AttestationError> for BootstrapSpecError {
    fn from(value: AttestationError) -> Self {
        match value {
            AttestationError::Truncated => Self::Truncated,
            AttestationError::TrailingBytes => Self::TrailingBytes,
            value => Self::Attestation(value),
        }
    }
}

